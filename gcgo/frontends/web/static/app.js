// --- jog & zero ---
function jog(...pairs) {
  let g = "$J=G91 G21";
  for (let i = 0; i < pairs.length; i += 2) {
    const axis = pairs[i], sign = pairs[i + 1];
    g += " " + axis + (sign === "-" ? "-" : "") + step;
  }
  g += " F" + (parseFloat($("jogfeed").value) || 1000);
  mdi(g);
}
// Virtual sticks (caPy jog mode). A stick movement goes out at once (at most
// one frame per STICK_MIN_MS), and a held stick repeats every 50 ms as its
// heartbeat -- complete state, newest wins: a dropped frame is harmless and the
// server zeroes a stick that goes quiet. Letting go sends one zero.
const STICK_MIN_MS = 16;
const stickv = { x: 0, y: 0, z: 0 };
let stickTimer = null, stickLast = 0, stickSoon = null;
function stickSend() {
  stickLast = performance.now();
  send({ cmd: "jog_vel", x: stickv.x, y: stickv.y, z: stickv.z,
         f: parseFloat($("jogfeed").value) || 1000 });
}
function stickSendSoon() {
  const wait = STICK_MIN_MS - (performance.now() - stickLast);
  if (wait <= 0) stickSend();
  else if (!stickSoon) stickSoon = setTimeout(() => { stickSoon = null; stickSend(); }, wait);
}
function stickPad(id, axes) {
  const pad = $(id), knob = pad.firstElementChild;
  const move = (e) => {
    const r = pad.getBoundingClientRect();
    const hw = r.width / 2, hh = r.height / 2, travel = Math.min(hw, hh);
    let dx = axes[0] ? (e.clientX - r.left - hw) / travel : 0;
    let dy = (e.clientY - r.top - hh) / (axes[0] ? travel : hh - travel / 2);
    const m = Math.hypot(dx, dy);
    if (m > 1) { dx /= m; dy /= m; }
    knob.style.transform = "translate(" + dx * travel + "px," +
                           dy * (axes[0] ? travel : hh - travel / 2) + "px)";
    if (axes[0]) { stickv.x = dx; stickv.y = -dy; } else stickv.z = -dy;
    stickSendSoon();
  };
  const up = () => {
    pad.classList.remove("held");
    knob.style.transform = "";
    if (axes[0]) { stickv.x = 0; stickv.y = 0; } else stickv.z = 0;
    if (!document.querySelector(".stick.held")) { clearInterval(stickTimer); stickTimer = null; }
    stickSend();
  };
  pad.addEventListener("pointerdown", (e) => {
    if (running) return;
    pad.setPointerCapture(e.pointerId);
    pad.classList.add("held");
    move(e);
    if (!stickTimer) stickTimer = setInterval(stickSend, 50);
  });
  pad.addEventListener("pointermove", (e) => { if (pad.classList.contains("held")) move(e); });
  pad.addEventListener("pointerup", up);
  pad.addEventListener("pointercancel", up);
}
stickPad("stickxy", [true]);
stickPad("stickz", [false]);

function zero(...axes) {
  mdi("G10 L20 P0 " + axes.map((a) => a + "0").join(" "));
}

// jog step selector
document.addEventListener("click", (e) => {
  const b = e.target.closest("#stepseg button");
  if (!b) return;
  for (const x of b.parentElement.children) x.classList.toggle("on", x === b);
  step = parseFloat(b.dataset.step);
});
function applyOverrides(ov) {
  for (const g of ["feed", "rapid", "spindle", "toggles"]) {
    const row = $("ovrow-" + g);
    if (row) row.style.display = ov[g] === false ? "none" : "";
  }
}

// --- files ---
function upDir() {
  const parent = curdir.includes("/") ? curdir.slice(0, curdir.lastIndexOf("/")) : "";
  send({ cmd: "files", dir: parent });
}
function refresh() { send({ cmd: "files", dir: curdir }); }
function newDir() {
  const name = prompt("New folder name:");
  if (name && name.trim()) send({ cmd: "mkdir", dir: curdir, name: name.trim() });
}
function runSel() { if (sel) send({ cmd: "run", file: sel }); }
function dlSel() { if (sel) window.location = "/dl?file=" + encodeURIComponent(sel); }
function delSel() {
  if (sel && confirm("Delete " + sel + "?")) {
    send({ cmd: "delete", file: sel }); sel = null;
    $("sel").textContent = "no file selected"; $("sel").style.color = "var(--mut)";
  }
}

async function upload(input) {
  for (const f of input.files) {
    log("uploading " + f.name + " …", "sys");
    try {
      const url = "/upload?name=" + encodeURIComponent(f.name) +
                  "&dir=" + encodeURIComponent(curdir);
      const r = await fetch(url, { method: "POST", body: f });
      if (!r.ok) log("upload failed: " + (await r.text()), "err");
    } catch (err) { log("upload error: " + err, "err"); }
  }
  input.value = "";
  refresh();
}

// --- console ---
function mdi(line) {
  line = (line || "").trim();
  if (!line) return;
  log("> " + line, "tx");
  send({ cmd: "mdi", line });
}
function log(line, cls) {
  const el = $("log");
  const span = document.createElement("span");
  span.className = cls || "rx";
  span.textContent = line + "\n";
  el.appendChild(span);
  el.scrollTop = el.scrollHeight;
}

