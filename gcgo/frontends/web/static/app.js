"use strict";
const $ = (id) => document.getElementById(id);
let ws, curdir = "", sel = null, loaded = null;
let step = 1, running = false;

function connect() {
  ws = new WebSocket("ws://" + location.host + "/ws");
  ws.onmessage = (e) => handle(JSON.parse(e.data));
  ws.onopen = () => log("connected", "sys");
  ws.onclose = () => { setState("offline"); setTimeout(connect, 1000); };
}
function send(o) { if (ws && ws.readyState === 1) ws.send(JSON.stringify(o)); }

function setState(s) {
  const el = $("state");
  el.textContent = s;
  el.className = "badge " + (s || "").split(":")[0];
}
const join = (d, n) => (d ? d + "/" + n : n);

function handle(m) {
  if (m.type === "status") {
    setState(m.state || "—");
    const u = m.units;
    $("unitlbl").textContent = u;
    setAxis("x", m.wpos[0], m.mpos[0]);
    setAxis("y", m.wpos[1], m.mpos[1]);
    setAxis("z", m.wpos[2], m.mpos[2]);
    $("feed").textContent = m.feed.toFixed(0) + (u === "in" ? " in/m" : " mm/m");
    $("spindle").textContent = m.spindle.toFixed(0) + " rpm";
    $("ovf").textContent = m.ov[0] + "%";
    $("ovr").textContent = m.ov[1] + "%";
    $("ovs").textContent = m.ov[2] + "%";
    $("pins").textContent = m.pins || "-";
    const st = m.stream;
    running = st.state === "running" || st.state === "finishing";
    $("prog").value = st.progress;
    if (st.state === "running")
      $("progtxt").textContent = st.sent + " sent · " + (st.progress * 100).toFixed(0) + "%";
    else if (st.state === "finishing")
      $("progtxt").textContent = "end of file · finishing motion";
    else
      $("progtxt").textContent = st.state + (m.loaded ? "  (" + m.loaded + ")" : "");
    loaded = m.loaded;
  } else if (m.type === "files") {
    curdir = m.dir || "";
    renderFiles(m.entries || []);
  } else if (m.type === "settings") {
    // settings are edited on /settings.html; here we only honor which
    // override groups to show
    applyOverrides(m.overrides || {});
  } else if (m.type === "msg") {
    let cls = /^(error|ALARM|\[MSG:.*rror)/i.test(m.line) ? "err" : "rx";
    if (m.line.includes("\x1b[30;47m")) cls = "qr";   // a row of $help's QR code
    const why = explain(m.line);
    const line = tidy(m.line);
    log(why ? line + "  — " + why : line, cls);
  }
}

// Error/alarm code text (codes.json, generated by tools/sync_capy.py). Matches
// GRBL's "error:N" / "ALARM:N" and caPy's "error:N ; Message".
let codes = { errors: {}, alarms: {} };
fetch("/codes.json").then((r) => r.json()).then((j) => { codes = j; }).catch(() => {});
function explain(line) {
  const m = /^(error|ALARM):\s*(\d+)\s*(?:;.*)?$/.exec(line);
  if (!m) return "";
  return (m[1] === "ALARM" ? codes.alarms : codes.errors)[m[2]] || "";
}

// caPy's "$" reply rows come as "[$:text]": show the text, minus the ANSI
// colour codes of $help's QR code (its rows get the "qr" class instead).
function tidy(line) {
  if (line.startsWith("[$:") && line.endsWith("]")) line = line.slice(3, -1);
  return line.replace(/\x1b\[[0-9;]*m/g, "");
}

function setAxis(a, w, mc) {
  $("w" + a).textContent = w.toFixed(3);
  $("m" + a).textContent = "M " + mc.toFixed(3);
}

const ICON_DIR = '<svg class="ic" viewBox="0 0 16 16" fill="currentColor"><path d="M1.5 3.5A1.5 1.5 0 0 1 3 2h3l1.5 1.5H13A1.5 1.5 0 0 1 14.5 5v6.5A1.5 1.5 0 0 1 13 13H3a1.5 1.5 0 0 1-1.5-1.5z"/></svg>';
const ICON_FILE = '<svg class="ic" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.3"><path d="M4 1.5h5L13 5v9.5H4z"/><path d="M9 1.5V5h4"/></svg>';

function renderFiles(entries) {
  $("cwd").textContent = "/" + curdir;
  const box = $("files");
  box.innerHTML = "";
  if (!entries.length) {
    const e = document.createElement("div");
    e.className = "entry"; e.style.color = "var(--mut)"; e.textContent = "(empty)";
    box.appendChild(e); return;
  }
  for (const e of entries) {
    const row = document.createElement("div");
    row.className = "entry" + (e.d ? " dir" : "");
    row.innerHTML = (e.d ? ICON_DIR : ICON_FILE) + "<span></span>";
    row.lastChild.textContent = e.n;
    const rel = join(curdir, e.n);
    if (e.d) {
      row.onclick = () => send({ cmd: "files", dir: rel });
    } else {
      if (rel === sel) row.classList.add("sel");
      row.onclick = () => {
        sel = rel;
        $("sel").textContent = rel;
        $("sel").style.color = "var(--txt)";
        for (const el of box.querySelectorAll(".sel")) el.classList.remove("sel");
        row.classList.add("sel");
      };
    }
    box.appendChild(row);
  }
}

